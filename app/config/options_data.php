/** 按角色返回职称字典（无职称角色返回空数组） */
function opt_titles($role) {
    $map = array(
        'doctor'  => 'title_doctor',
        'nurse'   => 'title_nurse',
        'lab'     => 'title_lab',
        'imaging' => 'title_imaging',
    );
    return isset($map[$role]) ? opt_list($map[$role]) : array();
}

/** 生成 <option> 下拉选项 HTML（供视图直接使用） */
function opt_options($key, $selected = '', $emptyText = '请选择') {
    $html = '<option value="">' . e($emptyText) . '</option>';
    foreach (opt_list($key) as $v) {
        $sel = ((string)$v === (string)$selected) ? ' selected' : '';
        $html .= '<option value="' . e($v) . '"' . $sel . '>' . e($v) . '</option>';
    }
    return $html;
}
