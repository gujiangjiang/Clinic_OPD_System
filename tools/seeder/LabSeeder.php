    public function run() {
        $created = 0;
        $stmt = $this->pdo->prepare('SELECT id FROM lab_items WHERE name=?');
        $ins = $this->pdo->prepare('INSERT INTO lab_items(category,name,unit,price,normal_range,status,created_at) VALUES(?,?,?,?,?,?,?)');
        foreach ($this->defs as $row) {
            $stmt->execute(array($row[1]));
            if (!$stmt->fetchColumn()) {
                $ins->execute(array($row[0], $row[1], $row[2], $row[3], $row[4], 'approved', now_str()));
                $created++;
            }
        }
        $total = (int)$this->pdo->query("SELECT COUNT(*) FROM lab_items WHERE status='approved' AND is_group=0")->fetchColumn();
        $this->out('新增 ' . $created . ' 项，共 ' . $total . ' 项检验项目');
        return $created;
    }
