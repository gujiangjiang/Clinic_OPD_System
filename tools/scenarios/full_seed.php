                'progress', $initialId, '', '', '', '', '', '', '', '否',
                (string)$consDiag['diagnosis_code'], (string)$consDiag['diagnosis_name'],
                json_encode($consEmr, JSON_UNESCAPED_UNICODE), $consPrint,
                'done', $consTime, $consTime, $consultId,
            ]);
            $consRecordId = (int)$pdo->lastInsertId();
            $recordCount++;
            $pdo->prepare("INSERT INTO records(visit_id, patient_no, flow_no, dept_id, doctor_id, doctor_name, preliminary_diagnosis, icd10_code, visit_type, doctor_advice, status, created_at, updated_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?)")->execute([
                $visitId, $p['patient_no'], $flowNo, $tDept['id'], $cDoc['id'], $cDoc['name'],
                $consDiag['diagnosis_name'], $consDiag['diagnosis_code'], '会诊', $consEmr['advice'], 'done', $consTime, $consTime,
            ]);
        }
    }

    // ==================== 多人续写（诊毕 + opts.multiDoc） ====================
    if (!empty($opts['multiDoc']) && $status === 'finished') {
        $writers = $doctorPool;
        shuffle($writers);
        $nWriters = mt_rand(1, 2);
        $usedW = [$doc['id'] => 1];
        $wCount = 0;
        $parent = $initialId;
        $wTime = strtotime($recUpdated);
        foreach ($writers as $w) {
            if ($wCount >= $nWriters) break;
            if (isset($usedW[$w['id']])) continue;
            $usedW[$w['id']] = 1;
            $wCount++;
            $wTime += mt_rand(1800, 7200);
            $wTimeStr = date('Y-m-d H:i:s', $wTime);
            $wDiags = [];
            if (mt_rand(1, 100) <= 60) {
                $wDiags[] = $diagPick[0];
                if (mt_rand(1, 100) <= 40) {
                    $dg2 = $diagPool[array_rand($diagPool)];
                    $wDiags[] = ['code' => $dg2['diagnosis_code'], 'name' => $dg2['diagnosis_name'], 'part' => '', 'note' => '', 'suspected' => ''];
                }
            }
            $wEmr = emr_default_data(null);
            $wEmr['progress'] = ['content' => $progPool[array_rand([0, 1, 2, 3, 4])]];
            $wEmr['diagnoses'] = $wDiags;
            $wEmr['advice'] = $advicePool[array_rand([0, 1, 2, 3, 4, 5])];
            $wPrint = emr_print_text($wEmr, '', '', [], [], []);
            $wDiagText = count($wDiags) ? emr_diag_text($wDiags) : '';
            $pdo->prepare("INSERT INTO patient_records(visit_id, patient_no, flow_no, dept_id, doctor_id, doctor_name, record_type, parent_record_id, chief_complaint, symptom_duration, symptom_unit, informant, arrival_way, has_past_history, allergy_history, is_leave_hospital, icd10_code, diagnosis_name, emr_data, emr_print_text, status, created_at, updated_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)")->execute([
                $visitId, $p['patient_no'], $flowNo, $deptId, $w['id'], $w['name'],
                'progress', $parent, '', '', '', '', '', '', '', '否',
                count($wDiags) ? (string)$wDiags[0]['code'] : '',
                count($wDiags) ? (string)$wDiags[0]['name'] : '',
                json_encode($wEmr, JSON_UNESCAPED_UNICODE), $wPrint,
                'done', $wTimeStr, $wTimeStr,
            ]);
            $parent = (int)$pdo->lastInsertId();
            $recordCount++;
            $pdo->prepare("INSERT INTO records(visit_id, patient_no, flow_no, dept_id, doctor_id, doctor_name, chief_complaint, present_illness, consciousness, preliminary_diagnosis, icd10_code, visit_type, status, created_at, updated_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)")->execute([
                $visitId, $p['patient_no'], $flowNo, $deptId, $w['id'], $w['name'],
                '', '', '', $wDiagText, count($wDiags) ? (string)$wDiags[0]['code'] : '', '', 'done', $wTimeStr, $wTimeStr,
            ]);
        }
    }

    // 诊断证明（少量诊毕）
    if ($status === 'finished' && mt_rand(1, 100) <= 12) {
        $cTs = strtotime($recUpdated) + mt_rand(600, 3000);
        $certNo = seed_gen_no('ZM', $pdo, 'certificates', 'cert_no');
        $pdo->prepare("INSERT INTO certificates(visit_id, patient_no, flow_no, doctor_id, doctor_name, content, created_at, cert_no, chief_complaint, present_illness, preliminary_diagnosis) VALUES(?,?,?,?,?,?,?,?,?,?,?)")->execute([
            $visitId, $p['patient_no'], $flowNo, $doc['id'], $doc['name'],
            $advicePool[array_rand([0, 1, 2])],
            date('Y-m-d H:i:s', $cTs), $certNo, $ccRow[0], $emr['history_present']['content'], $diagText,
        ]);
    }

    return $visitId;
}

