            $consEmr = emr_default_data(null);
            $consEmr['progress'] = ['content' => '会诊意见：结合患者病史及辅助检查，' . $ccRow[0] . '考虑' . $consDiag['diagnosis_name'] . '，建议' . (mt_rand(0, 1) ? '继续目前治疗' : '调整治疗方案') . '。'];
