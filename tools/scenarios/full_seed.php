function seed_gen_no($prefix, $pdo, $table, $col) {
    do {
        $no = $prefix . date('YmdHis') . str_pad((string)mt_rand(0, 999), 3, '0', STR_PAD_LEFT);
        $stmt = $pdo->prepare("SELECT COUNT(*) FROM $table WHERE $col=?");
        $stmt->execute([$no]);
        if ((int)$stmt->fetchColumn() === 0) return $no;
    } while (true);
}

function gen_id_card() {
    $prefix = '110101' . '19' . str_pad(mt_rand(70, 99), 2, '0', STR_PAD_LEFT) .
              str_pad(mt_rand(1, 12), 2, '0', STR_PAD_LEFT) .
              str_pad(mt_rand(1, 28), 2, '0', STR_PAD_LEFT);
    $body = $prefix . str_pad(mt_rand(100, 999), 3, '0', STR_PAD_LEFT);
    $weights = [7,9,10,5,8,4,2,1,6,3,7,9,10,5,8,4,2];
    $sum = 0;
    for ($i = 0; $i < 17; $i++) $sum += (int)$body[$i] * $weights[$i];
    $check = '10X98765432'[$sum % 11];
    return $body . $check;
}

