    // pending/paid：只挂号缴费，不接诊
    if (!in_array($status, ['visiting', 'finished'], true)) return $visitId;

    // ==================== 病历（开单前置） ====================
    $ccRow = $ccPoolAll[array_rand($ccPoolAll)];
    $diagCand = pickDiagByDept($deptId, $diagPool, $deptDiagKw);
    $diagPick = [];
    $used = [];
    $nDiag = mt_rand(1, min(3, count($diagCand)));
    for ($q = 0; $q < $nDiag; $q++) {
        $dg = $diagCand[array_rand($diagCand)];
        if (isset($used[$dg['code']])) continue;
        $used[$dg['code']] = 1;
        $diagPick[] = [
            'code' => $dg['code'], 'name' => $dg['name'],
            'part' => (mt_rand(1, 100) <= 25 ? ['左侧', '右侧', '右上肢', '左下肢'][array_rand([0, 1, 2, 3])] : ''),
            'note' => (mt_rand(1, 100) <= 15 ? '外伤所致' : ''),
            'suspected' => (mt_rand(1, 100) <= 10 ? '是' : ''),
        ];
    }
    if (!count($diagPick)) {
        $dg = $diagPool[array_rand($diagPool)];
        $diagPick[] = ['code' => $dg['diagnosis_code'], 'name' => $dg['diagnosis_name'], 'part' => '', 'note' => '', 'suspected' => ''];
    }

    // 生命体征
    $consciousness = $conscPool[array_rand($conscPool)];
    $sys = mt_rand(95, 165); $dia = mt_rand(60, 100); $hr = mt_rand(58, 110);
    $spo2 = mt_rand(93, 100); $resp = mt_rand(14, 22);
    $vTime = date('Y-m-d H:i:s', $ts + mt_rand(300, 1500));
    $pdo->prepare("INSERT INTO vitals(visit_id, patient_no, flow_no, vital_sbp, vital_dbp, vital_heart_rate, vital_pulse, vital_spo2, vital_respiration, operator, created_at) VALUES(?,?,?,?,?,?,?,?,?,?,?)")->execute([
        $visitId, $p['patient_no'], $flowNo, $sys, $dia, $hr, $hr, $spo2, $resp, $doc['name'], $vTime,
    ]);
    $vitalCount++;
    $vitalsText = '血压 ' . $sys . '/' . $dia . 'mmHg；心率 ' . $hr . '次/分；血氧 ' . $spo2 . '%；呼吸 ' . $resp . '次/分';

    // 首诊结构化病历
    $emr = emr_default_data(null);
    $emr['chief_complaint'] = ['symptom' => $ccRow[0], 'duration' => $ccRow[1], 'unit' => $ccRow[2], 'second_symptom' => $ccRow[3], 'second_duration' => $ccRow[4], 'second_unit' => $ccRow[5]];
    // 现病史：时间只出现一次（供史者+时长由 emr_pi_text 拼在 content 前，
    // content 以「前」开头承接，避免「患者自诉2天患者于2天前」重复时间）；
    // 内容末尾不加句号（打印时系统自动追加逗号接来院途径）。
    $informant = ['患者自诉', '家属代诉'][array_rand([0, 1])];
    $emr['history_present'] = [
        'informant' => $informant,
        'duration' => $ccRow[1], 'unit' => $ccRow[2],
        'content' => '前无明显诱因出现' . $ccRow[0] . '，' . $ccRow[3] . $ccRow[4] . $ccRow[5] . '，' . rtrim($piTails[array_rand([0, 1, 2, 3, 4])], '。'),
