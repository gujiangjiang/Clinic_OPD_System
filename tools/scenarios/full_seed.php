                $visitId, $p['patient_no'], $flowNo, $consNo,
                $deptId, $dept['name'], $doc['id'], $doc['name'],
                $tDept['id'], $tDept['name'],
                '患者' . $ccRow[0] . '，' . $diagPick[0]['name'] . '，请贵科会诊协助评估处理方案。',
                '协助评估诊断及进一步治疗方案。',
                'done', $cDoc['name'], date('Y-m-d H:i:s', $cTs + mt_rand(600, 3600)), $cDoc['name'], date('Y-m-d H:i:s', $cTs + mt_rand(7200, 18000)), 0, date('Y-m-d H:i:s', $cTs),
            ]);
            $consultId = (int)$pdo->lastInsertId();
            $consCount++;
            // 会诊病历（会诊医生写 progress）
