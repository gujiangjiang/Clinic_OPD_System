                        if (count($parts) === 2 && is_numeric($parts[0]) && is_numeric($parts[1])) {
                            $vals[$itemId] = round((float)$parts[0] + ((float)$parts[1] - (float)$parts[0]) * (mt_rand() / mt_getrandmax()), 1);
                        }
                    }
                }
                $valuesJson = ($otype === 'lab' && count($vals)) ? json_encode(['values' => $vals], JSON_UNESCAPED_UNICODE) : '{}';
                $resTs = strtotime($execAt) + mt_rand(600, 3600);
                $findings = $otype === 'imaging' ? ['所见骨质结构完整，未见明显骨折征象。', '双肺纹理增粗，余未见明显异常。', '软组织肿胀，未见明显异物存留。', '未见明显异常。'][array_rand([0, 1, 2, 3])] : '';
