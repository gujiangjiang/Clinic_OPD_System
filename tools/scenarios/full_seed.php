function makeVisit($p, $deptId, $ts, $status, $opts = array()) {
        global $pdo, $deptMap, $doctorPool, $staff, $diagPool, $deptDiagKw,
           $ccPoolAll, $piTails, $pePool, $advicePool, $progPool, $wardPool, $hospPool, $deathPool, $conscPool,
