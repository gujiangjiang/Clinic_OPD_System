           $recordCount, $orderCount, $itemCount, $resultCount, $vitalCount, $consCount;

    $dept = isset($deptMap[$deptId]) ? $deptMap[$deptId] : null;
    if (!$dept) return 0;
    $day = date('Y-m-d', $ts);
    $dayPrefix = date('ymd', $ts);

    // 本科室医生
    $docPool = array_values(array_filter($doctorPool, function ($d) use ($deptId) {
        return in_array($deptId, $d['depts'], true);
    }));
    if (!count($docPool)) $docPool = $doctorPool;
    $doc = $docPool[array_rand($docPool)];

    // 号段续号
    $stmt = $pdo->prepare("SELECT MAX(CAST(substr(flow_no,7) AS INTEGER)) FROM registrations WHERE substr(flow_no,1,6)=?");
    $stmt->execute([$dayPrefix]);
    $flowMax = (int)$stmt->fetchColumn();
    $flowNo = $dayPrefix . str_pad((string)($flowMax + 1), 4, '0', STR_PAD_LEFT);
    $stmt = $pdo->prepare("SELECT MAX(visit_seq) FROM registrations WHERE first_dept_id=? AND date(registered_at)=?");
    $stmt->execute([$deptId, $day]);
    $visitSeq = (int)$stmt->fetchColumn() + 1;

    $fee = $dept['type'] === 'emergency' ? 50 : ($deptId === 6 ? 0 : 20);
    $paid = in_array($status, ['paid', 'visiting', 'finished'], true);
    $payTime = $paid ? date('Y-m-d H:i:s', $ts + mt_rand(120, 900)) : '';
    $disp = ''; $dispDetail = ''; $finishedAt = '';
    if ($status === 'finished') {
        $r2 = mt_rand(1, 100);
        if ($r2 <= 60) { $disp = '自主离院'; }
        elseif ($r2 <= 78) { $disp = '住院'; $dispDetail = $wardPool[array_rand($wardPool)]; }
