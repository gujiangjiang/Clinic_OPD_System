    $phType = ['否认', '否认', '承认'][array_rand([0, 1, 2])];
    $emr['past_history'] = ['type' => $phType, 'detail' => $phType === '承认' ? ['高血压病史5年', '2型糖尿病史3年', '慢性胃炎病史'][array_rand([0, 1, 2])] : ''];
