                $pdo->prepare("INSERT INTO results(item_id, order_item_id, visit_id, patient_no, flow_no, type, values_json, findings, conclusion, executor, status, created_at, updated_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?)")->execute([
                    $itemId, $iid, $visitId, $p['patient_no'], $flowNo, $otype, $valuesJson,
                    $findings, $conclusion, $execBy, 'done', date('Y-m-d H:i:s', $resTs), date('Y-m-d H:i:s', $resTs),
                ]);
                $resultId = (int)$pdo->lastInsertId();
                $dayKey = date('Ymd', $resTs);
                $stmt = $pdo->prepare("SELECT MAX(CAST(substr(report_no,11) AS INTEGER)) FROM reports WHERE substr(report_no,3,8)=?");
                $stmt->execute([$dayKey]);
                $repSeq = (int)$stmt->fetchColumn() + 1;
                $reportNo = 'BG' . $dayKey . str_pad((string)$repSeq, 4, '0', STR_PAD_LEFT);
                $pdo->prepare("INSERT INTO reports(result_id, report_no, visit_id, patient_no, flow_no, type, content, doctor, status, apply_dept, apply_doctor, clinical_diag, apply_time, reg_time, category_name, created_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)")->execute([
                    $resultId, $reportNo, $visitId, $p['patient_no'], $flowNo, $otype, '',
                    $execBy, 'done', $dept['name'], $doc['name'], $diagPick[0]['name'],
                    $created, $execAt, $otype === 'imaging' ? (isset($ex['category']) ? $ex['category'] : '') : '', date('Y-m-d H:i:s', $resTs),
                ]);
                $pdo->prepare("UPDATE order_items SET result_id=? WHERE id=?")->execute([$resultId, $iid]);
                if ($otype === 'imaging') {
                    $modality = strpos($ir['item_name'], 'CT') !== false ? 'CT' : (strpos($ir['item_name'], 'MRI') !== false ? 'MR' : (strpos($ir['item_name'], '超声') !== false || strpos($ir['item_name'], '彩超') !== false ? 'US' : 'DR'));
                    $pdo->prepare("INSERT INTO imaging_refs(order_item_id, order_id, visit_id, patient_no, flow_no, study_uid, series_uids, instance_count, modality, region, meta_json, created_by, created_at, updated_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)")->execute([
                        $iid, $orderId, $visitId, $p['patient_no'], $flowNo,
                        $reportNo, '[]', 0, $modality, 'region-pacs', '{}', $execBy, date('Y-m-d H:i:s', $resTs), date('Y-m-d H:i:s', $resTs),
                    ]);
                }
                $resultCount++;
            }
        }
    }

    // 开单缴费流水
    foreach ($visitOrders as $vo) {
        if ($vo['status'] !== 'open') {
            $st = $pdo->prepare("SELECT total_amount FROM orders WHERE id=?");
            $st->execute([$vo['id']]);
            $orderTotal = (float)$st->fetchColumn();
            $pdo->prepare("INSERT INTO payments(visit_id, order_id, patient_no, flow_no, kind, total, item_count, cashier_id, cashier_name, created_at) VALUES(?,?,?,?,?,?,?,?,?,?)")->execute([
                $visitId, $vo['id'], $p['patient_no'], $flowNo, 'order', $orderTotal, 1, 2, $staff['cashier'], $vo['paid_at'],
            ]);
        }
    }

    // ==================== 病历落库（patient_records + records 双镜像） ====================
    $printText = emr_print_text($emr, $vitalsText, $consciousness, $auxNames, $rxLines, $dispItems);
    $diagText = emr_diag_text($diagPick);
    $pdo->prepare("INSERT INTO patient_records(visit_id, patient_no, flow_no, dept_id, doctor_id, doctor_name, record_type, parent_record_id, chief_complaint, symptom_duration, symptom_unit, informant, arrival_way, has_past_history, allergy_history, is_leave_hospital, icd10_code, diagnosis_name, emr_data, emr_print_text, status, created_at, updated_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)")->execute([
        $visitId, $p['patient_no'], $flowNo, $deptId, $doc['id'], $doc['name'],
        'initial', 0, $ccRow[0], $ccRow[1], $ccRow[2], $emr['history_present']['informant'], $emr['history_present']['arrival_way'],
        $emr['past_history']['type'], '', '否', (string)$diagPick[0]['code'], (string)$diagPick[0]['name'],
        json_encode($emr, JSON_UNESCAPED_UNICODE), $printText,
        $status === 'finished' ? 'done' : 'draft', $recCreated, $recUpdated,
    ]);
    $initialId = (int)$pdo->lastInsertId();
    $recordCount++;
    $pdo->prepare("INSERT INTO records(visit_id, patient_no, flow_no, dept_id, doctor_id, doctor_name, chief_complaint, present_illness, past_history, allergy_history, physical_exam, consciousness, preliminary_diagnosis, icd10_code, is_observation, visit_type, doctor_advice, status, created_at, updated_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)")->execute([
        $visitId, $p['patient_no'], $flowNo, $deptId, $doc['id'], $doc['name'],
        $ccRow[0], $emr['history_present']['content'], $emr['past_history']['detail'], '',
        // 体格检查：结构化节点（其它体格检查）内容兼容提取，避免缺 'content' 键告警
        (isset($emr['physical_exam']['content']) ? $emr['physical_exam']['content'] : (is_array($emr['physical_exam']) ? implode('，', $emr['physical_exam']) : (string)$emr['physical_exam'])), $consciousness, $diagText, (string)$diagPick[0]['code'],
        $deptId == 5 ? 1 : 0, '初诊', $emr['advice'],
        $status === 'finished' ? 'done' : 'draft', $recCreated, $recUpdated,
    ]);

    // ==================== 会诊（诊毕 + opts.consult） ====================
    if (!empty($opts['consult']) && $status === 'finished') {
        $cTs = strtotime($recCreated) + mt_rand(300, 1800);
        $cDoc = $doctorPool[array_rand($doctorPool)];
        $targetDeptId = $deptId == 5 ? 2 : 5;
        $tDept = isset($deptMap[$targetDeptId]) ? $deptMap[$targetDeptId] : null;
        if ($tDept) {
